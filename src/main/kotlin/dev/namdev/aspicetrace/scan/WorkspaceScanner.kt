package dev.namdev.aspicetrace.scan

import dev.namdev.aspicetrace.model.ArtifactKind
import dev.namdev.aspicetrace.model.Reference
import dev.namdev.aspicetrace.model.Requirement
import dev.namdev.aspicetrace.model.ScanResult
import java.io.IOException
import java.nio.file.FileSystems
import java.nio.file.FileVisitResult
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.PathMatcher
import java.nio.file.SimpleFileVisitor
import java.nio.file.attribute.BasicFileAttributes
import kotlin.io.path.invariantSeparatorsPathString

data class ScanConfig(
    val idPattern: Regex,
    // Glob patterns relative to the root, such as "samples/**" or "third_party".
    val excludes: List<String> = emptyList(),
    /** Absolute paths never to scan, such as the report output directory. */
    val ignoredPaths: Set<Path> = emptySet(),
    val tag: String = ReferenceScanner.DEFAULT_TAG,
)

/** Walks a source tree and collects requirement definitions (specs) and references (code and tests). */
// @Requirement TRC-SCAN-003 TRC-CLI-002
class WorkspaceScanner(private val config: ScanConfig) {

    private val specParser = SpecParser(config.idPattern)
    private val referenceScanner = ReferenceScanner(config.idPattern, config.tag)
    private val excludeMatchers: List<PathMatcher> =
        config.excludes.map { FileSystems.getDefault().getPathMatcher("glob:$it") }
    private val ignoredPaths: Set<Path> = config.ignoredPaths.map { it.toAbsolutePath().normalize() }.toSet()

    fun scan(root: Path): ScanResult {
        val base = root.toAbsolutePath().normalize()
        val definitions = mutableListOf<Requirement>()
        val references = mutableListOf<Reference>()
        val skipped = mutableListOf<String>()
        var scanned = 0

        for (file in collectFiles(base)) {
            val relative = base.relativize(file)
            val kind = FileClassifier.classify(relative) ?: continue
            val path = relative.invariantSeparatorsPathString
            val lines = readUtf8(file)
            when {
                lines == null -> skipped += path
                kind == ArtifactKind.SPEC && isGeneratedReport(lines) -> Unit
                kind == ArtifactKind.SPEC -> definitions += specParser.parse(path, lines).also { scanned++ }
                else -> references += referenceScanner.scan(path, kind, lines).also { scanned++ }
            }
        }
        return ScanResult(definitions, references, scanned, skipped)
    }

    /** Sorted, so reports are identical for identical input. */
    private fun collectFiles(base: Path): List<Path> {
        val files = mutableListOf<Path>()
        Files.walkFileTree(
            base,
            object : SimpleFileVisitor<Path>() {
                override fun preVisitDirectory(dir: Path, attrs: BasicFileAttributes): FileVisitResult {
                    val skip = dir != base &&
                        (dir.fileName.toString() in IGNORED_DIRECTORIES || dir in ignoredPaths || isExcluded(base, dir))
                    return if (skip) FileVisitResult.SKIP_SUBTREE else FileVisitResult.CONTINUE
                }

                override fun visitFile(file: Path, attrs: BasicFileAttributes): FileVisitResult {
                    if (attrs.isRegularFile && !isExcluded(base, file)) files.add(file)
                    return FileVisitResult.CONTINUE
                }

                override fun visitFileFailed(file: Path, exc: IOException): FileVisitResult = FileVisitResult.CONTINUE
            },
        )
        return files.sortedBy { base.relativize(it).invariantSeparatorsPathString }
    }

    private fun isExcluded(base: Path, path: Path): Boolean {
        val relative = base.relativize(path)
        return excludeMatchers.any { it.matches(relative) }
    }

    @Suppress("SwallowedException")
    private fun readUtf8(file: Path): List<String>? = try {
        Files.readAllLines(file, Charsets.UTF_8)
    } catch (e: IOException) {
        null // Unreadable or not UTF-8 (a binary file with a source extension); reported as skipped.
    }

    private fun isGeneratedReport(lines: List<String>): Boolean =
        lines.firstOrNull()?.contains(GENERATED_MARKER) == true

    companion object {
        /** First line of every Markdown report this tool writes, so a report is never parsed as a spec. */
        const val GENERATED_MARKER = "<!-- generated by aspice-trace -->"

        val IGNORED_DIRECTORIES = setOf(".git", ".gradle", ".idea", ".kotlin", "build", "node_modules", "trace-report")
    }
}
