/** A single self-contained HTML page: summary, filterable matrix, unknown references and duplicates. */
// @Requirement TRC-RPT-001
class HtmlReport(
    private val projectName: String,
    private val linker: Linker = Linker { null },
) {

    fun render(report: TraceReport): String = buildString {
        appendLine("<!doctype html>")
        appendLine("""<html lang="en"><head><meta charset="utf-8">""")
        appendLine("""<meta name="viewport" content="width=device-width, initial-scale=1">""")
        appendLine("<title>Traceability: ${escapeHtml(projectName)}</title>")
        appendLine("<style>$CSS</style>")
        appendLine("</head><body><main>")
        appendLine("<header><p class=\"eyebrow\">Traceability matrix</p><h1>${escapeHtml(projectName)}</h1></header>")
        appendSummary(report)
        appendMatrix(report)
        appendLocationTable(
            title = "Unknown references",
            note = "Cited by code or tests, but not defined in any spec (broken backward traceability).",
            header = "Referenced at",
            entries = report.unknownReferences,
        )
        appendLocationTable(
            title = "Duplicate definitions",
            note = "Defined more than once; the first definition is used in the matrix.",
            header = "Defined at",
            entries = report.duplicateDefinitions,
        )
        appendLine("<footer>Generated by aspice-trace ${Version.NAME} from ${report.filesScanned} files.</footer>")
        appendLine("</main><script>$SCRIPT</script></body></html>")
    }

    private fun StringBuilder.appendSummary(report: TraceReport) {
        appendLine("<section class=\"cards\">")
        card("Requirements", report.requirementCount.toString(), "defined in specs")
        card("Implemented", "${report.implementedPercent}%", "${report.implementedCount} of ${report.requirementCount}")
        card("Verified", "${report.verifiedPercent}%", "${report.verifiedCount} of ${report.requirementCount}")
        val gaps = report.gapCount
        card("Gaps", gaps.toString(), if (gaps == 0) "nothing to fix" else "to fix", alert = gaps > 0)
        appendLine("</section>")
    }

    private fun StringBuilder.card(label: String, value: String, detail: String, alert: Boolean = false) {
        val css = if (alert) "card alert" else "card"
        appendLine(
            "<div class=\"$css\"><span class=\"label\">$label</span><span class=\"value\">$value</span>" +
                "<span class=\"detail\">$detail</span></div>",
        )
    }

    private fun StringBuilder.appendMatrix(report: TraceReport) {
        appendLine("<section><h2>Matrix</h2>")
        appendLine("<div class=\"controls\">")
        appendLine("""<input id="q" type="search" placeholder="Filter by ID, title or file" """)
        appendLine("""aria-label="Filter rows">""")
        appendLine("""<select id="status" aria-label="Filter by status"><option value="">All statuses</option>""")
        TraceStatus.entries.forEach { appendLine("<option value=\"${it.cssClass}\">${it.label}</option>") }
        appendLine("""</select><span id="count" aria-live="polite"></span></div>""")
        appendLine("<div class=\"scroll\"><table id=\"matrix\"><thead><tr>")
        appendLine("<th>Requirement</th><th>Title</th>")
        ArtifactKind.entries.forEach { appendLine("<th>${escapeHtml(it.label)}</th>") }
        appendLine("<th>Status</th></tr></thead><tbody>")
        report.rows.forEach { appendRow(it) }
        appendLine("</tbody></table></div></section>")
    }

    private fun StringBuilder.appendRow(row: TraceRow) {
        val status = row.status
        appendLine("<tr data-status=\"${status.cssClass}\">")
        appendLine("<td class=\"id\">${escapeHtml(row.requirement.id)}</td>")
        appendLine("<td class=\"title\">${escapeHtml(row.requirement.title)}</td>")
        appendLine("<td>${locations(listOf(row.requirement.location))}</td>")
        appendLine("<td>${locations(row.implementedBy)}</td>")
        appendLine("<td>${locations(row.verifiedBy)}</td>")
        appendLine("<td><span class=\"badge ${status.cssClass}\">${status.label}</span></td></tr>")
    }

    private fun StringBuilder.appendLocationTable(
        title: String,
        note: String,
        header: String,
        entries: Map<String, List<Location>>,
    ) {
        if (entries.isEmpty()) return
        appendLine("<section><h2>$title <span class=\"pill\">${entries.size}</span></h2><p class=\"note\">$note</p>")
        appendLine("<div class=\"scroll\"><table><thead><tr><th>Requirement</th><th>$header</th></tr></thead><tbody>")
        entries.forEach { (id, where) ->
            appendLine("<tr><td class=\"id\">${escapeHtml(id)}</td><td>${locations(where)}</td></tr>")
        }
        appendLine("</tbody></table></div></section>")
    }

    private fun locations(list: List<Location>): String {
        if (list.isEmpty()) return "<span class=\"none\">none</span>"
        // Show "File.kt:12" to keep the matrix readable; the full path is in the tooltip.
        return list.joinToString("<br>") { location ->
            val full = escapeHtml(location.toString())
            val short = escapeHtml("${location.path.substringAfterLast('/')}:${location.line}")
            val href = linker.href(location)
            if (href == null) {
                "<code title=\"$full\">$short</code>"
            } else {
                "<a href=\"${escapeHtml(href)}\" title=\"$full\"><code>$short</code></a>"
            }
        }
    }
}

internal fun escapeHtml(text: String): String = buildString(text.length) {
    text.forEach { char ->
        when (char) {
            '&' -> append("&amp;")
            '<' -> append("&lt;")
            '>' -> append("&gt;")
            '"' -> append("&quot;")
            '\'' -> append("&#39;")
            else -> append(char)
        }
    }
}

