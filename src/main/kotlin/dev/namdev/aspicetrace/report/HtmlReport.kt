private const val SCRIPT = """
(function(){
  var q=document.getElementById('q'),s=document.getElementById('status'),c=document.getElementById('count');
  var rows=Array.prototype.slice.call(document.querySelectorAll('#matrix tbody tr'));
  function apply(){
    var t=q.value.trim().toLowerCase(),n=0;
    rows.forEach(function(r){
      var show=(!s.value||r.getAttribute('data-status')===s.value)&&(!t||r.textContent.toLowerCase().indexOf(t)>=0);
      r.hidden=!show;if(show){n++;}
    });
    c.textContent=n+' of '+rows.length+' requirements';
  }
  q.addEventListener('input',apply);s.addEventListener('change',apply);apply();
})();
"""
